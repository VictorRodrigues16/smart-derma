async function main() {
  const senha = process.env.SENHA_DEMO || 'SmartDerma#2026'
  const senhaHash = await bcrypt.hash(senha, 10)

  const contas = await prisma.usuario.createMany({
    data: (Object.entries(CONTAS_DEMO) as [keyof typeof CONTAS_DEMO, (typeof CONTAS_DEMO)[keyof typeof CONTAS_DEMO]][]).map(
      ([papel, conta]) => ({ email: conta.email, nome: conta.nome, senhaHash, papel }),
    ),
    skipDuplicates: true,
  })

  const produtos = await prisma.produto.createMany({
    data: PRODUTOS.map((p) => ({
      ...p,
      evitarGestante: p.evitarGestante ?? false,
      evitarSensivel: p.evitarSensivel ?? false,
      apenasAdulto: p.apenasAdulto ?? false,
      ativo: true,
    })),
    skipDuplicates: true,
  })

  console.log(`Seed: ${contas.count} contas e ${produtos.count} produtos criados (o que já existia ficou como estava).`)
}

main()
  .catch((erro) => {
    console.error(erro)
    process.exit(1)
  })
  .finally(() => prisma.$disconnect())
